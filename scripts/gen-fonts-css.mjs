// Generates src/styles/fonts.css: @font-face rules for the built-in fonts, taken from their
// Fontsource packages but limited to the latin, latin-ext and (Arabic fonts) arabic files, so the
// installer doesn't carry every alphabet. Run with `pnpm fonts:css` after adding or updating a
// font package. The list below must match BUILTIN_FONTS in src/lib/fonts.ts (fonts.test.ts
// checks the generated CSS against it).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src', 'styles', 'fonts.css');

// Static packages ship one file per weight; only these weights are bundled.
const STATIC_WEIGHTS = [400, 700];

const FONTS = [
  { id: 'inter', variable: true },
  { id: 'open-sans', variable: true },
  { id: 'jetbrains-mono', variable: true },
  { id: 'roboto', variable: true },
  { id: 'noto-sans', variable: true },
  { id: 'source-sans-3', variable: true },
  { id: 'lato', variable: false },
  { id: 'atkinson-hyperlegible-next', variable: true },
  { id: 'merriweather', variable: true },
  { id: 'lora', variable: true },
  { id: 'source-serif-4', variable: true },
  { id: 'montserrat', variable: true },
  { id: 'playfair-display', variable: true },
  { id: 'fira-code', variable: true },
  { id: 'source-code-pro', variable: true },
  { id: 'ibm-plex-mono', variable: false },
  { id: 'noto-sans-arabic', variable: true, arabic: true },
  { id: 'noto-naskh-arabic', variable: true, arabic: true },
  { id: 'ibm-plex-sans-arabic', variable: false, arabic: true },
];

/** The CSS files of a package to read, relative to the package folder. */
function cssFiles(font, pkgDir) {
  const names = font.variable
    ? ['wght.css', 'wght-italic.css']
    : STATIC_WEIGHTS.flatMap((w) => [`${w}.css`, `${w}-italic.css`]);
  return names.filter((n) => existsSync(join(pkgDir, n)));
}

/** Rewrites one @font-face block: woff2 only, URL pointing into node_modules. */
function convertBlock(block, font, pkgName, allowed) {
  const woff2 = /url\(\.\/files\/([^)]+\.woff2)\)\s*format\('([^']+)'\)/.exec(block);
  if (!woff2) throw new Error(`No woff2 source in a ${font.id} block`);
  const [, file, format] = woff2;
  const subset = new RegExp(`^${font.id}-(.+?)-(?:wght|\\d+)-(?:normal|italic)\\.woff2$`).exec(
    file,
  )?.[1];
  if (!subset) throw new Error(`Can't read the subset from ${file}`);
  if (!allowed.has(subset)) return null;
  const url = `../../node_modules/${pkgName}/files/${file}`;
  return block.replace(/src:[^;]+;/, `src: url(${url}) format('${format}');`);
}

const out = [
  '/* Generated by scripts/gen-fonts-css.mjs. Do not edit by hand.',
  '   Regenerate with `pnpm fonts:css` after adding or updating a font package.',
  '   Only the latin, latin-ext and (Arabic fonts) arabic files are included. */',
  '',
];

for (const font of FONTS) {
  const pkgName = `${font.variable ? '@fontsource-variable' : '@fontsource'}/${font.id}`;
  const pkgDir = join(root, 'node_modules', pkgName);
  if (!existsSync(pkgDir)) throw new Error(`${pkgName} is not installed`);
  const allowed = new Set(['latin', 'latin-ext', ...(font.arabic ? ['arabic'] : [])]);
  for (const name of cssFiles(font, pkgDir)) {
    const css = readFileSync(join(pkgDir, name), 'utf8').replace(/\r\n/g, '\n');
    for (const block of css.match(/\/\*[^*]*\*\/\s*@font-face\s*\{[^}]*\}/g) ?? []) {
      const converted = convertBlock(block, font, pkgName, allowed);
      if (converted) out.push(converted, '');
    }
  }
}

writeFileSync(outFile, out.join('\n'));
console.log(`Wrote ${outFile}`);
